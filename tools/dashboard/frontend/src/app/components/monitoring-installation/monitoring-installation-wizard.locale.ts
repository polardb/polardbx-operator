export function getWizardLocale(localeId: string | null | undefined): WizardLocaleDictionary {
  if (!localeId) {
    return wizardLocaleZhCn;
  }
  const normalized = localeId.toLowerCase();
  if (normalized.startsWith('en')) {
    return wizardLocaleEnUs;
  }
  if (normalized.startsWith('zh')) {
    return wizardLocaleZhCn;
  }
  return wizardLocaleZhCn;
}

export function translateWizard(
  locale: WizardLocaleDictionary,
  key: string,
  params?: Record<string, string | number>
): string {
  let template = locale[key] ?? wizardLocaleZhCn[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([paramKey, value]) => {
      const regex = new RegExp(`{{\\s*${paramKey}\\s*}}`, 'g');
      template = template.replace(regex, String(value));
    });
  }
  return template;
}
